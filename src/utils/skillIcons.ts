const rawSkillIcon = (name: string): SkillIcon =>
   SKILL_ICONS[name] ?? { Icon: Network, color: BLUE };

export const getSkillIconColor = (
   name: string,
   mode: "uniform" | "brand" = SKILL_ICON_MODE,
): string => (mode === "uniform" ? SKILL_ICON_COLOR : rawSkillIcon(name).color);

export const getSkillIcon = (name: string): SkillIcon => ({
   ...rawSkillIcon(name),
   color: getSkillIconColor(name),
});

export const getSkillIconNames = (): string[] => Object.keys(SKILL_ICONS);
